    /**
     * Constructs a TestResult object with the given test name, resource URL, and test value.
     * The constructor generates a unique URN for the test result, sets the title and
     * description based on the test name, and initializes other fields such as license,
     * completion percentage, assessment target, log, output from test, generated at time,
     * and was generated by information.  
     * 
     * @param testName the name of the test that was run, used to set the title and
     * description of the test result
     * @param resourceUrl the URL of the resource that was assessed, used to set the assessment target 
     * and 'was generated by' information
     * @param result the result of the test, typically an enum value representing the outcome,
     * used to set the value field of the test result
     */
    public TestResult(String name, String resourceUrl, Result result) {
        String urn = "urn:cessda:" + UUID.randomUUID().toString();
        this.id = urn;
        this.identifier = urn;  // identifier should match @id
        this.testName = name;
        this.value = result.toString();
        this.log = getLogMessage(result);
        this.title = "Output from running test: " + name +
                " (https://fair-tests.cessda.eu/assess/test/" + name + ")";
        this.license = new License("http://creativecommons.org/licenses/by/4.0/");
        this.completion = new Completion(getCompletionPercentage(result));
        this.assessmentTarget = new AssessmentTarget(resourceUrl);
        this.outputFromTest = new OutputFromTest("https://fair-tests.cessda.eu/assess/test/" + testName);
        this.generatedAtTime = new GeneratedAtTime();
        this.wasGeneratedBy = new WasGeneratedBy(resourceUrl, name, this);
        this.description = wasGeneratedBy.getWasAssociatedWith().getDescription();
    }


    /**
     * Helper method
     * @param result
     * @return
     */
    private int getCompletionPercentage (Result result) {
        switch (result) {
            case PASS:
                return 100;
            case FAIL:
                return 100;
            case INDETERMINATE:
                return 0;
            default:
                return 0;
        }
    }


    /**
     * Helper method to generate a log message based on the test result.
     * This method takes a Result enum value as input
     * 
     * @param result the result of the test, typically an enum value representing the outcome
     * @return a log message string that describes the outcome of the test based on the provided result
     */
    private String getLogMessage (Result result) {
        switch (result) {
            case PASS:
                return "Test passed successfully.";
            case FAIL:
                return "Test failed.";
            case INDETERMINATE:
                return "Test result is indeterminate.";
            default:
                return "Unknown test result.";
        }
    }

