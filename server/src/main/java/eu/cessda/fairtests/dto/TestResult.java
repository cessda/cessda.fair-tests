        private String identifier;
        private String title;
        private String apiDescription = "https://fair-tests.cessda.eu/api/";
        private String description;

        @JsonProperty("endpointDescription")
        private EndpointDescription endpointDescription;

        @JsonProperty("endpointURL")
        private EndpointURL endpointURL;

        public WasAssociatedWith(String testName, TestResult result) {
            this.id = result.testEndpoint + testName;
            this.identifier = this.id;
            this.title = getTestTitle(testName);
            this.description = getTestDescription(testName);
            this.endpointDescription = new EndpointDescription(
                    apiDescription + testName + ".ttl");
            this.endpointURL = new EndpointURL(result.testEndpoint + testName);
        }

        /**
         * Helper method to load test metadata from the corresponding Turtle
         * file for the given test name. This method attempts to read the
         * Turtle file associated with the test, extract the title and
         * description from the file's content, and return them as a map.
         * If the file does not exist or cannot be read, it returns default
         * metadata based on the test name.    
         * 
         * @param testName the name of the test for which to load metadata
         * @return a map containing the title and description of the test,
         *         either loaded from the Turtle file or generated based on
         *         the test name if the file is not available.    
         */
        private Map<String, String> loadTestMetadata(String testName) {
            Map<String, String> metadata = new HashMap<>();
            metadata.put("title", "Test: " + testName);
            metadata.put("description", "This test verifies " + testName);

            try {
                String filename = testName + ".ttl";
                ClassPathResource resource = new ClassPathResource("static/" + filename);

                if (!resource.exists()) {
                    return metadata;
                }

                Yaml yaml = new Yaml();
                try (InputStream inputStream = resource.getInputStream()) {
                    Map<String, Object> data = yaml.load(inputStream);

                    // Safe extraction using helper method
                    String title = extractStringValue(data, "info", "title");
                    if (title != null) {
                        metadata.put("title", title);
                    }

                    String description = extractStringValue(data, "info", "description");
                    if (description != null) {
                        metadata.put("description", description);
                    }
                }

            } catch (Exception e) {
                e.printStackTrace();
            }

            return metadata;
        }

        /**
         * Safely extract a nested string value from a map structure
         * given a sequence of keys. This method traverses the map
         * using the provided keys, checking at each step whether the
         * current value is a map and whether the next key exists.
         * 
         * @param map the map from which to extract the value
         * @param keys the sequence of keys to navigate through the map
         * @return the extracted string value if found, or null if any
         *         key is missing or if the final value is not a string
         */
        private String extractStringValue(Map<String, Object> map, String... keys) {
    Object current = map;

    for (String key : keys) {
        if (!(current instanceof Map)) {
            return null;
        }
        current = ((Map<?, ?>) current).get(key);
        if (current == null) {
            return null;
        }
    }
    
    if (current instanceof String) {
        String value = (String) current;
        // Strip leading and trailing quotes if present
        if (value.startsWith("\"") && value.endsWith("\"") && value.length() > 1) {
            return value.substring(1, value.length() - 1);
        }
        return value;
    }
    
    return null;
}

        /**
         * Helper method to load test metadata from the
         * corresponding Turtle file for the given test name.
         * This method attempts to read the Turtle file associated with the test,
         * extract the title and description from the file's content, and return them as
         * a map.
         * If the file does not exist or cannot be read, it returns default metadata
         * based on the test name.
         * 
         * @param testName the name of the test for which to load metadata
         * @return a map containing the title and description of the test,
         *         either loaded from the Turtle file or generated based on the test
         *         name if the file is not available
         */
        private String getTestTitle(String testName) {
            return loadTestMetadata(testName).get("title");
        }

        /**
         * Helper method to load the test description from the
         * corresponding Turtle file for the given test name.
         * This method uses the loadTestMetadata method to retrieve the description,
         * which may be extracted from the Turtle file or generated based on the
         * test name if the file is not available.
         *
         * @param testName the name of the test for which to load the description
         * @return the description of the test, either loaded from the Turtle file
         *         or generated based on the test name if the file is not available
         */
        private String getTestDescription(String testName) {
            return loadTestMetadata(testName).get("description");
        }

